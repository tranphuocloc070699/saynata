package com.englishtranslation.backend.migration;

import static org.assertj.core.api.Assertions.assertThat;

import com.englishtranslation.backend.cache.CacheKeys;
import java.util.List;
import java.util.Map;
import javax.sql.DataSource;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/**
 * Flyway V29 (TASK-106.6): Vietnamese translations of cached sentences become language lines (source seed), only for
 * text that is normalized the way Java does it; sentences the prefill job answered go back to pending.
 */
class SeedLineTranslationMigrationTest {

    @Test
    void vietnameseTranslationsBecomeSeedLinesAndPrefillSentencesAreQueuedAgain() {
        DataSource dataSource = new DriverManagerDataSource("jdbc:h2:mem:seed_lines_v29;DB_CLOSE_DELAY=-1", "sa", "");
        Flyway.configure().dataSource(dataSource).locations("classpath:db/migration").target("27").load().migrate();
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        // H2 rejects rows in the V17 table because of its CHECK clauses (see RequeueSentencePrefillMigrationTest).
        jdbc.execute("drop table prefill_item");
        jdbc.execute("create table prefill_item (id bigint generated by default as identity primary key, "
                + "kind varchar(10) not null, text varchar(500) not null, status varchar(16) not null, "
                + "attempts int not null, last_error text, updated_at timestamp with time zone, source varchar(32))");

        sentence(jdbc, "k1", "How are you?", "vi", "Bạn khỏe không?", "2026-01-01 10:00:00");
        // The same text twice: the newest row wins.
        sentence(jdbc, "k2", "How are you?", "vi", "Bạn có khỏe không?", "2026-02-01 10:00:00");
        // Not Vietnamese: not copied.
        sentence(jdbc, "k3", "Good night", "ja", "おやすみ", "2026-01-01 10:00:00");
        // Not normalized (double space, trailing space): the line service would hash another text, so skipped.
        sentence(jdbc, "k4", "See  you", "vi", "Hẹn gặp lại", "2026-01-01 10:00:00");
        sentence(jdbc, "k5", "See you ", "vi", "Hẹn gặp lại", "2026-01-01 10:00:00");
        // An empty translation is not a line.
        sentence(jdbc, "k6", "Empty one", "vi", "", "2026-01-01 10:00:00");
        jdbc.update("insert into prefill_item (kind, text, status, attempts, source) values ('sentence', 'Not yet.', "
                + "'done', 1, 'test')");
        jdbc.update("insert into prefill_item (kind, text, status, attempts, source) values ('word', 'giraffe', "
                + "'done', 1, 'test')");

        Flyway.configure().dataSource(dataSource).locations("classpath:db/migration").load().migrate();

        List<Map<String, Object>> lines = jdbc.queryForList(
                "select text_hash, text, target_lang, prompt_version, translation, source from line_translation");
        assertThat(lines).hasSize(1);
        Map<String, Object> line = lines.get(0);
        assertThat(line.get("TEXT_HASH")).isEqualTo(CacheKeys.key("How are you?"));
        assertThat(line.get("TEXT")).isEqualTo("How are you?");
        assertThat(line.get("TARGET_LANG")).isEqualTo("vi");
        assertThat(line.get("PROMPT_VERSION")).isEqualTo("v1");
        assertThat(line.get("TRANSLATION")).isEqualTo("Bạn có khỏe không?");
        assertThat(line.get("SOURCE")).isEqualTo("seed");

        assertThat(jdbc.queryForObject("select status from prefill_item where text = 'Not yet.'", String.class))
                .isEqualTo("pending");
        assertThat(jdbc.queryForObject("select status from prefill_item where text = 'giraffe'", String.class))
                .isEqualTo("done");
    }

    private static void sentence(JdbcTemplate jdbc, String key, String text, String lang, String translation,
            String createdAt) {
        jdbc.update("insert into sentence_translation (cache_key, source_text, translation, model, prompt_version,"
                + " created_at, target_lang, match_key, meaning, words_json) values (?, ?, ?, 'm', 'v9', ?, ?, ?, 'x', '[]')",
                key, text, translation, java.sql.Timestamp.valueOf(createdAt), lang,
                CacheKeys.sentenceMatchKey("v9", lang, text));
    }
}
