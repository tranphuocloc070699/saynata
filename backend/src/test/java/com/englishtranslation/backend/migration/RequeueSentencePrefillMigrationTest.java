package com.englishtranslation.backend.migration;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Connection;
import java.sql.SQLException;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

/**
 * Flyway V26 (TASK-89.3): every answered sentence goes back to the prefill queue for prompt v9; words stay done.
 * H2 rejects rows in the V17 table because of its CHECK clauses, so the table here has the same columns without
 * them, and only the V26 script runs.
 */
class RequeueSentencePrefillMigrationTest {

    @Test
    void doneSentencesArePendingAgainAndNothingElseChanges() throws SQLException {
        DriverManagerDataSource dataSource = new DriverManagerDataSource("jdbc:h2:mem:requeue_v9;DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("create table prefill_item (id bigint generated by default as identity primary key, "
                + "kind varchar(10) not null, text varchar(500) not null, status varchar(16) not null, "
                + "attempts int not null, last_error text, updated_at timestamp with time zone)");
        insert(jdbc, "sentence", "Not yet.", "done", 1, "old error");
        insert(jdbc, "sentence", "Looks good.", "failed", 3, "timeout");
        insert(jdbc, "sentence", "Sounds fair.", "pending", 0, null);
        insert(jdbc, "word", "giraffe", "done", 1, null);

        try (Connection connection = dataSource.getConnection()) {
            ScriptUtils.executeSqlScript(connection,
                    new ClassPathResource("db/migration/V26__requeue_sentence_prefill_for_prompt_v9.sql"));
        }

        assertThat(row(jdbc, "Not yet.")).isEqualTo("pending/0/null");
        assertThat(row(jdbc, "Looks good.")).isEqualTo("failed/3/timeout");
        assertThat(row(jdbc, "Sounds fair.")).isEqualTo("pending/0/null");
        assertThat(row(jdbc, "giraffe")).isEqualTo("done/1/null");
    }

    private static void insert(JdbcTemplate jdbc, String kind, String text, String status, int attempts, String error) {
        jdbc.update("insert into prefill_item (kind, text, status, attempts, last_error) values (?, ?, ?, ?, ?)",
                kind, text, status, attempts, error);
    }

    private static String row(JdbcTemplate jdbc, String text) {
        return jdbc.queryForObject("select status || '/' || attempts || '/' || coalesce(last_error, 'null') "
                + "from prefill_item where text = ?", String.class, text);
    }
}
