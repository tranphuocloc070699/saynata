-- TASK-83.1: the queue of words and phrases the prefill job answers before users ask.
-- Written by the pipeline (prefill collect) and by admins; read by prefill/PrefillRunner.
CREATE TABLE prefill_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(10)              NOT NULL CHECK (kind IN ('word', 'sentence')),
    text        VARCHAR(500)             NOT NULL,
    target_lang VARCHAR(8)               NOT NULL DEFAULT '',
    source      VARCHAR(32)              NOT NULL,
    priority    INT                      NOT NULL DEFAULT 0,
    status      VARCHAR(16)              NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done', 'skipped', 'failed')),
    attempts    INT                      NOT NULL DEFAULT 0,
    last_error  TEXT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_prefill_item UNIQUE (kind, text, target_lang)
);
CREATE INDEX idx_prefill_item_queue ON prefill_item (status, priority DESC, id);
