--
-- 1. media.source may now be 'ai'. The V13 check has a different automatic name in Postgres and in H2 (the
--    backend tests), so the column is made again with the new check instead of dropping the constraint by name.
ALTER TABLE media ADD COLUMN source_new VARCHAR(16) NOT NULL DEFAULT 'pixabay'
    CHECK (source_new IN ('pixabay', 'upload', 'ai'));
UPDATE media SET source_new = source;
ALTER TABLE media DROP COLUMN source;
ALTER TABLE media RENAME COLUMN source_new TO source;

-- 2. One row per AI image the pipeline made, also the ones that are never linked (a trial, a picture the
--    developer did not like). media_id is set when the image is linked to its sense; the media row then has
--    source = 'ai' and the sense gets media_status = 'ai_generated'. The pipeline writes this table; the
--    backend does not read it yet.
CREATE TABLE media_generation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sense_id      BIGINT                   NOT NULL REFERENCES dictionary_sense (id) ON DELETE CASCADE,
    file_name     VARCHAR(128)             NOT NULL UNIQUE,   -- for example apple_1_ai_1a2b3c4d.webp
    provider      VARCHAR(32)              NOT NULL,          -- openai
    model         VARCHAR(64)              NOT NULL,          -- gpt-image-1-mini
    prompt        TEXT                     NOT NULL,
    input_tokens  INTEGER                  NOT NULL,
    output_tokens INTEGER                  NOT NULL,
    cost_usd      NUMERIC(10, 6)           NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    old_media_id  BIGINT                   REFERENCES media (id) ON DELETE SET NULL,   -- the picture it replaces
    media_id      BIGINT                   REFERENCES media (id) ON DELETE SET NULL,   -- set when linked
    linked_at     TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_media_generation_sense ON media_generation (sense_id, created_at DESC);
