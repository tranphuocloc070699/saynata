-- TASK-92: sign in with Google, with Apple, and with an emailed link.

-- One row per outside account (a Google or an Apple account) that signs in to one of our users.
-- subject is the provider's own stable id of the person ("sub" in the ID token); the email can change.
CREATE TABLE user_identity (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider   VARCHAR(20)              NOT NULL,
    subject    VARCHAR(255)             NOT NULL,
    email      VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_user_identity_provider_subject UNIQUE (provider, subject)
);
CREATE INDEX idx_user_identity_user ON user_identity (user_id);

-- The sign-in link last emailed to one address. Only the SHA-256 of the link token is saved.
-- code_challenge is the SHA-256 of a secret the app kept, so only the app that asked can use the link.
CREATE TABLE email_login_link (
    token_hash     VARCHAR(64)              NOT NULL PRIMARY KEY,
    email          VARCHAR(255)             NOT NULL,
    code_challenge VARCHAR(64)              NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_email_login_link_email ON email_login_link (email);
