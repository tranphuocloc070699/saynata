-- TASK-78: the Claude vision check of sense pictures and clips (pipeline: uv run pipeline media-check).
-- One row per check, so a sense checked again (--recheck) keeps its history. The newest row for the sense's
-- current media is the one that counts. The pipeline writes this table; the backend does not read it yet.
CREATE TABLE media_check (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sense_id      BIGINT                   NOT NULL REFERENCES dictionary_sense (id) ON DELETE CASCADE,
    media_id      BIGINT                   REFERENCES media (id) ON DELETE SET NULL,   -- the file that was checked
    verdict       VARCHAR(8)               NOT NULL CHECK (verdict IN ('good', 'wrong', 'unsure')),
    reason        TEXT                     NOT NULL,   -- one short sentence from Claude
    model         VARCHAR(64)              NOT NULL,
    checked_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    input_tokens  INTEGER                  NOT NULL,
    output_tokens INTEGER                  NOT NULL,
    cost_usd      NUMERIC(10, 6)           NOT NULL
);

CREATE INDEX idx_media_check_sense ON media_check (sense_id, checked_at DESC);
