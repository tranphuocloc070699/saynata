-- TASK-67: one row per Claude call, with the real token counts and the cost worked out from the config prices.
CREATE TABLE claude_usage (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    model         VARCHAR(100)             NOT NULL,
    feature       VARCHAR(20)              NOT NULL,
    input_tokens  BIGINT                   NOT NULL,
    output_tokens BIGINT                   NOT NULL,
    cost_usd      NUMERIC(14, 8)           NOT NULL
);
CREATE INDEX idx_claude_usage_created_at ON claude_usage (created_at);
