-- TASK-49.3: the bundled dictionary (about 2,750 NGSL words) lives in Postgres.
-- Postgres is the source of truth. The pipeline imports dictionary.sqlite once and later exports a new
-- dictionary.sqlite from these tables (pipeline: import-to-postgres, export).
-- word_lookup stays: it holds the words the backend asked Claude about.

-- Media rows. The FILES are not in the database: they live on disk (on the VPS in a Docker volume).
CREATE TABLE media (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name     VARCHAR(128)             NOT NULL UNIQUE,   -- for example run_1.mp4
    kind          VARCHAR(8)               NOT NULL CHECK (kind IN ('photo', 'clip')),
    width         INTEGER,
    height        INTEGER,
    bytes         BIGINT,
    pixabay_id    BIGINT,
    photographer  VARCHAR(255),                               -- Pixabay user name (attribution)
    page_url      VARCHAR(500),                               -- Pixabay page of the file (attribution)
    license_note  VARCHAR(255),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE dictionary_word (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lemma          VARCHAR(64)              NOT NULL UNIQUE,
    word_rank      INTEGER                  NOT NULL,         -- NGSL rank, lower = more common
    ipa            VARCHAR(128),
    needs_review   BOOLEAN                  NOT NULL DEFAULT FALSE,
    model          VARCHAR(64),
    prompt_version VARCHAR(16),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

-- One meaning of a word. examples_json and usage_json hold the same JSON lists the app reads from
-- dictionary.sqlite: [{"level": "easy", "text": "..."}] and [{"kind": "...", "pattern": "...", "example": "..."}].
CREATE TABLE dictionary_sense (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id           BIGINT       NOT NULL REFERENCES dictionary_word (id) ON DELETE CASCADE,
    position          INTEGER      NOT NULL,
    pos               VARCHAR(32)  NOT NULL,
    cefr              VARCHAR(8)   NOT NULL,
    simple_definition TEXT         NOT NULL,
    vietnamese        TEXT         NOT NULL,
    examples_json     TEXT         NOT NULL,
    usage_json        TEXT         NOT NULL,
    image_type        VARCHAR(16)  NOT NULL,
    image_query       VARCHAR(255) NOT NULL,
    media_id          BIGINT       REFERENCES media (id) ON DELETE SET NULL,
    UNIQUE (word_id, position)
);

-- "ran" -> run, with its type ("past tense", "plural", ... or "form").
CREATE TABLE dictionary_form (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id   BIGINT      NOT NULL REFERENCES dictionary_word (id) ON DELETE CASCADE,
    form      VARCHAR(64) NOT NULL,
    form_type VARCHAR(32) NOT NULL
);

CREATE INDEX idx_dictionary_sense_media ON dictionary_sense (media_id);
CREATE INDEX idx_dictionary_form_word ON dictionary_form (word_id);

-- The admin list filters by CEFR level. A backend word keeps the level of its first sense in this column
-- (filled when the entry is saved; rows from before this migration are filled once at start-up).
ALTER TABLE word_lookup ADD COLUMN cefr VARCHAR(8);

-- One list for the admin web app: bundled words ("b-12") and backend words ("w-45").
-- The level of a bundled word is the level of its first sense.
CREATE VIEW admin_word_list AS
SELECT 'b-' || CAST(w.id AS VARCHAR(20)) AS item_id,
       'bundled'                         AS source,
       w.id                              AS source_id,
       w.lemma                           AS word,
       w.ipa                             AS ipa,
       w.needs_review                    AS needs_review,
       w.model                           AS model,
       w.prompt_version                  AS prompt_version,
       w.created_at                      AS created_at,
       (SELECT s.cefr FROM dictionary_sense s WHERE s.word_id = w.id AND s.position = 0) AS cefr
FROM dictionary_word w
UNION ALL
SELECT 'w-' || CAST(l.id AS VARCHAR(20)),
       'backend',
       l.id,
       l.word,
       CAST(NULL AS VARCHAR(128)),
       l.needs_review,
       l.model,
       l.prompt_version,
       l.created_at,
       l.cefr
FROM word_lookup l;
