-- TASK-91: the admin draws an AI picture for one sense. The server runs the Codex CLI in the background; this table
-- is the job list. The admin page asks for the newest job of a sense and shows queued, drawing, done or failed.
--
-- word_id       the admin word id: "b-12" (bundled) or "w-45" (backend word), like /api/admin/words/{id}
-- position      0 = first sense
-- prompt        the image prompt the admin pressed OK on (the Codex wrapper text is added by the server)
-- prompt_source where the first prompt came from: scene (media-ai), template, claude (the wand) or edited
-- status        queued, drawing, done or failed
-- error         a plain sentence for the admin, when status = failed
-- media_id      the media row of the new picture (done). SET NULL when the picture is deleted later.
-- old_media_id  the picture it replaced
-- Kept simple for H2 (the backend tests): no JSON columns, no partial indexes.
CREATE TABLE ai_picture_job (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id       VARCHAR(24)              NOT NULL,
    position      INTEGER                  NOT NULL,
    prompt        TEXT                     NOT NULL,
    prompt_source VARCHAR(16)              NOT NULL,
    status        VARCHAR(16)              NOT NULL CHECK (status IN ('queued', 'drawing', 'done', 'failed')),
    error         TEXT,
    media_id      BIGINT                   REFERENCES media (id) ON DELETE SET NULL,
    old_media_id  BIGINT                   REFERENCES media (id) ON DELETE SET NULL,
    created_by    VARCHAR(255),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at    TIMESTAMP WITH TIME ZONE,
    finished_at   TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_ai_picture_job_sense ON ai_picture_job (word_id, position, created_at DESC);
