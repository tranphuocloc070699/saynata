-- TASK-93.1: the words and sentences a signed-in user starred. They follow the user to every device.
-- text_key is the normalized text (a word: lowercase, one space; a sentence: trimmed); text is what the user saw.
-- ON DELETE CASCADE: deleting the account deletes its liked items.
CREATE TABLE liked_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind       VARCHAR(10)              NOT NULL,
    text_key   VARCHAR(500)             NOT NULL,
    text       VARCHAR(500)             NOT NULL,
    preview    VARCHAR(300)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_liked_item_key UNIQUE (user_id, kind, text_key)
);
CREATE INDEX idx_liked_item_user_created ON liked_item (user_id, created_at DESC);
