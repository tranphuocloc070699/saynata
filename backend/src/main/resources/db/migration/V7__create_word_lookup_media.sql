-- TASK-49.4: media for backend words (word_lookup). One row per sense that the background job looked at.
-- The row is made BEFORE Pixabay is asked, so a sense is never asked twice (even when the answer was "nothing found"
-- or the download failed). media_id stays NULL until a file is saved.
-- Bundled words need no table: dictionary_sense.media_id (V6) already points to the media row.
CREATE TABLE word_lookup_media (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_lookup_id BIGINT                   NOT NULL REFERENCES word_lookup (id) ON DELETE CASCADE,
    sense_position INTEGER                  NOT NULL,   -- 0 = first sense, same order as entry_json
    media_id       BIGINT                   REFERENCES media (id) ON DELETE SET NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (word_lookup_id, sense_position)
);
