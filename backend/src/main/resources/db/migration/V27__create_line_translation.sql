-- TASK-106.2: the language line. A short text (a simple-English explanation or a sentence) turned into one short
-- natural line in a target language. Shared by all users: one row per (text, language, prompt version).
-- text_hash is the sha256 hex of the normalized text (trimmed, inner whitespace collapsed).
-- source says who wrote the line: llm (backend call), codex (pipeline, local Codex CLI) or seed.
CREATE TABLE line_translation (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text_hash      VARCHAR(64)              NOT NULL,
    text           VARCHAR(500)             NOT NULL,
    target_lang    VARCHAR(8)               NOT NULL,
    prompt_version VARCHAR(20)              NOT NULL,
    translation    TEXT                     NOT NULL,
    source         VARCHAR(10)              NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_line_translation_key UNIQUE (text_hash, target_lang, prompt_version)
);
