-- TASK-66: app users who sign in with an email code. No password, so the admin password hash may be empty.
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- One row per email: asking for a new code replaces the old one. Only a keyed hash of the code is saved.
CREATE TABLE email_login_code (
    email      VARCHAR(255)             NOT NULL PRIMARY KEY,
    code_hash  VARCHAR(64)              NOT NULL,
    attempts   INT                      NOT NULL DEFAULT 0,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Long-lived sign-in tokens. Only the SHA-256 of the token is saved. Used tokens are marked revoked (rotation).
CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64)              NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_refresh_token_user ON refresh_token (user_id);
