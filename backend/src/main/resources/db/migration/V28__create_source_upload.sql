-- TASK-108: the admin Sources page. The admin uploads a book (.txt or .md); the backend finds the words and phrases
-- that are not in the database yet and keeps them here, so the admin can pick some on a later request.
-- The text of the book is NEVER saved: only the title, the counts, and one candidate per line
-- (kind, word, times, zipf, snippet of at most 12 words, separated by tabs). The snippets are cleared after queueing.
CREATE TABLE source_upload (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(100)             NOT NULL,
    words_in_file INT                      NOT NULL,
    known         INT                      NOT NULL,
    new_words     INT                      NOT NULL,
    new_phrases   INT                      NOT NULL,
    names_skipped INT                      NOT NULL,
    candidates    TEXT                     NOT NULL,
    status        VARCHAR(10)              NOT NULL DEFAULT 'ready' CHECK (status IN ('ready', 'queued')),
    queued_count  INT                      NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    queued_at     TIMESTAMP WITH TIME ZONE
);

